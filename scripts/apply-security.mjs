const SEDAMB = '\u015f'; // s with cedilla (legacy)
const TEDAMB = '\u0163'; // t with cedilla (legacy)
const SCM = '\u0219';    // s with comma below (modern)
const TCM = '\u021b';    // t with comma below (modern)
