L.push('}');
L.push('');
L.push('/**');
L.push(' * Creeaza o cerere de confirmare (pentru FAZA 2+)');
L.push(' */');
L.push('export function createConfirmationRequest(');
L.push('  action: string,');
L.push('  description: string,');
L.push('  affectedItems: number,');
L.push('  isIrreversible: boolean');
