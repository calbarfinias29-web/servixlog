L.push('');
L.push('/**');
L.push(' * =====================================================================');
L.push(' * FAZA 2A - CONFIRMATION FLOW SECURIZAT');
L.push(' * ---------------------------------------------------------------------');
L.push(' * PROBLEMA REZOLVATA:');
L.push(' *   Vechea logica folosea includes("confirm"), ceea ce producea un');
L.push(' *   FALSE POSITIVE periculos: "Nu confirm." (REFUZ) era tratat ca');
L.push(' *   aprobare, deoarece textul contine cuvantul "confirm".');
L.push(' *');
L.push(' * NOUA LOGICA:');
L.push(' *   1. REFUZUL EXPLICIT are PRIORITATE ABSOLUTA - niciun text cu o');
L.push(' *      negatie nu poate fi interpretat ca APPROVED.');
L.push(' *   2. Aprobarea necesita o formulare EXPLICITA (confirm / execut).');
L.push(' *   3. ORICE ALTCEVA (ok, bine, poate, cred ca da...) este AMBIGUU si');
L.push(' *      NU autorizeaza WRITE.');
L.push(' *');
L.push(' * Normalizarea PASTREAZA suportul pentru diacriticele romanesti');
L.push(` *   (${ABR} ${ACIR} ${ICIR} ${SCM} ${TCM}) si formele legacy (${SEDAMB} ${TEDAMB}).`);
L.push(' * WRITE ramane DEZACTIVAT: WRITE_ARMED === false.');
L.push(' * =====================================================================');
L.push(' */');
L.push('');
L.push('export interface ConfirmationDecision {');
L.push('  status: ConfirmationStatus;');
L.push('  reason: string;');
L.push('}');
L.push('');
L.push('/**');
L.push(' * Normalizeaza textul pastrand suportul pentru diacriticele romanesti.');
L.push(` * Converteste formele legacy (${SEDAMB}/${TEDAMB}) si scoate punctuia.`);
L.push(' */');
L.push('export function normalizeConfirmationText(text: string): string {');
L.push("  return String(text ?? '')");
L.push('    .toLowerCase()');
L.push("    .normalize('NFC')");
L.push(`    .replace(/[${SEDAMB}]/g, 's')`);
L.push(`    .replace(/[${TEDAMB}]/g, 't')`);
L.push(`    .replace(/${SCM}/g, 's')`);
L.push(`    .replace(/${TCM}/g, 't')`);
L.push(`    .replace(/${ABR}/g, 'a')`);
L.push(`    .replace(/${ACIR}/g, 'a')`);
L.push(`    .replace(/${ICIR}/g, 'i')`);
L.push("    .replace(/[^a-z0-9 ]/g, ' ')");
L.push("    .replace(/\\s+/g, ' ')");
L.push('    .trim();');
L.push('}');
L.push('');
//__CHUNK_B__
L.push('const APPROVED_PHRASES: ReadonlyArray<string> = [');
L.push("  'da',");
L.push("  'da confirm',");
L.push("  'da confirm modificarea',");
L.push("  'confirm',");
L.push("  'confirm modificarea',");
L.push("  'confirmarea',");
L.push("  'confirmare',");
L.push("  'executa',");
L.push("  'sigur',");
L.push("  'da da',");
L.push('];');
L.push('');
L.push('const NEGATION_WORDS: ReadonlyArray<string> = [');
L.push("  'nu',");
L.push("  'anuleaza',");
L.push("  'renunta',");
L.push("  'refuza',");
L.push("  'lasa',");
L.push("  'opreste',");
L.push('];');
L.push('');
L.push('function hasWord(text: string, word: string): boolean {');
L.push('  return new RegExp("(^| )" + word + "( |$)").test(text);');
L.push('}');
L.push('');
L.push('/**');
L.push(' * Clasifica raspunsul utilizatorului:');
L.push(' *  - approved  -> confirmare explicita;');
L.push(' *  - rejected  -> refuz explicit (prioritate absoluta);');
L.push(' *  - ambiguous -> nu autorizeaza in niciun caz WRITE.');
L.push(' */');
L.push('export function parseConfirmation(response: string): ConfirmationDecision {');
L.push('  const t = normalizeConfirmationText(response);');
L.push('  if (!t) {');
L.push("    return { status: 'ambiguous', reason: 'empty-or-whitespace' };");
L.push('  }');
L.push('');
L.push('  // 1) REFUZ EXPLICIT - PRIORITATE ABSOLUTA.');
L.push('  //    Orice negatie blocheaza definitiv WRITE pentru aceasta operatie,');
L.push('  //    chiar daca textul mai contine si cuvinte pozitive.');
L.push('  if (NEGATION_WORDS.some((w) => hasWord(t, w))) {');
L.push("    return { status: 'rejected', reason: 'explicit-refusal' };");
L.push('  }');
L.push('');
L.push('  // 2) CONFIRMARE EXPLICITA - potrivire stricta, NU includes.');
L.push('  if (APPROVED_PHRASES.includes(t)) {');
L.push("    return { status: 'approved', reason: 'explicit-approval' };");
L.push('  }');
L.push('');
L.push('  // Aprobari incepute cu "da", fara ezitare.');
L.push('  if (/^da(\\s|$)/.test(t)) {');
L.push("    const tail = t.replace(/^da/, '').trim();");
L.push("    if (tail === '' || /^(da|confirm|confirma|executa|sigur)/.test(tail)) {");
L.push("      return { status: 'approved', reason: 'explicit-approval' };");
L.push('    }');
L.push("    return { status: 'ambiguous', reason: 'hedged-approval' };");
L.push('  }');
L.push('');
L.push('  // Aprobari incepute cu verbul de comanda "confirma" / "executa".');
L.push('  if (/^(confirm|confirma|executa)/.test(t)) {');
L.push("    return { status: 'approved', reason: 'explicit-approval' };");
L.push('  }');
L.push('');
L.push('  // 3) ORICE ALTCEVA -> AMBIGUU. WRITE ramane BLOCAT.');
L.push("  return { status: 'ambiguous', reason: 'no-explicit-confirmation' };");
L.push('}');
L.push('');
L.push('/**');
